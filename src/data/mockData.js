/*
 * Each course is written as a compact config. buildCourse() expands the
 * modules into ids, flattens the lessons and calculates the total runtime so
 * the rest of the app can rely on a consistent shape.
 */
function buildCourse(config) {
  const modules = config.modules.map((module, moduleIndex) => {
    const moduleId = `${config.id}-m${moduleIndex + 1}`;
    return {
      id: moduleId,
      title: module.title,
      lessons: module.lessons.map(([title, minutes], lessonIndex) => ({
        id: `${moduleId}-l${lessonIndex + 1}`,
        moduleId,
        title,
        minutes,
      })),
    };
  });
  const lessons = modules.flatMap((module) => module.lessons);
  return {
    ...config,
    modules,
    lessons,
    totalMinutes: lessons.reduce((sum, lesson) => sum + lesson.minutes, 0),
  };
}

